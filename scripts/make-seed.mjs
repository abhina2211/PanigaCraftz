// Writes supabase/seed.sql from src/data/catalogue.js, so the database starts with
// exactly the products the site has today. Run: npm run seed
// Re-running the SQL updates products by id; it never deletes anything.
import { writeFileSync } from 'node:fs';
import { PRODUCTS } from '../src/data/catalogue.js';
import { persOf } from '../src/lib/rules.js';

const q = v => v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const row = p => {
  const pers = persOf(p);
  const details = { img: p.img, img2: p.img2, badge: p.badge, size: p.size || undefined, occ: p.occ, fest: p.fest, ig: p.ig, col: p.col, sample: p.sample };
  return `(${[
    p.id, p.slug, p.cat, p.ht ?? null, p.name, p.d,
    p.price == null ? null : Math.round(p.price * 100), !!p.priceFrom,
    // status: keep 'made'; otherwise let stock decide when stock is counted
    p.status === 'made' || p.stock == null ? p.status : null,
    !!pers, pers ? pers.label : null, pers ? pers.words : null,
    p.stock, !!p.hamper, !!p.builder
  ].map(q).join(', ')}, ${q(JSON.stringify(details))}::jsonb, ${p.added})`;
};

const sql = `-- Generated by scripts/make-seed.mjs from src/data/catalogue.js. Do not edit by hand.
-- Run after supabase/schema.sql. Placeholder prices and stock are marked "sample" in details.
insert into products (id, slug, category, hamper_type, name, description, price_cents, price_from, status,
  personalisable, personalisation_label, personalisation_word_limit, stock_qty, hamper_eligible, is_hamper_builder,
  details, sort_added)
values
${PRODUCTS.map(row).join(',\n')}
on conflict (id) do update set
  slug = excluded.slug, category = excluded.category, hamper_type = excluded.hamper_type, name = excluded.name,
  description = excluded.description, price_cents = excluded.price_cents, price_from = excluded.price_from,
  status = excluded.status, personalisable = excluded.personalisable,
  personalisation_label = excluded.personalisation_label, personalisation_word_limit = excluded.personalisation_word_limit,
  stock_qty = excluded.stock_qty, hamper_eligible = excluded.hamper_eligible, is_hamper_builder = excluded.is_hamper_builder,
  details = excluded.details, sort_added = excluded.sort_added, updated_at = now();
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${PRODUCTS.length} products`);
